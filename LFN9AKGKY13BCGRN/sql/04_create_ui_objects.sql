CREATE OR REPLACE VIEW MFQ_ASSIGNMENT_QUEUE_VW AS
SELECT
  ca.ASSIGNMENT_ID,
  ca.CLAIM_ID,
  c.PATIENT_NAME,
  d.DEFENDANT_NAME,
  d.SPECIALTY,
  ca.PRIORITY,
