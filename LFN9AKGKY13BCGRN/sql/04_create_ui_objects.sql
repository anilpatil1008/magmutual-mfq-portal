CREATE OR REPLACE VIEW MFQ_SECTIONS_VW AS
SELECT
  FORM_KEY,
  SECTION_ID,
  SECTION_KEY,
  SECTION_NAME,
  DISPLAY_ORDER,
  DISPLAY_ORDER AS SECTION_ORDER,
  IS_SKIPPABLE,
